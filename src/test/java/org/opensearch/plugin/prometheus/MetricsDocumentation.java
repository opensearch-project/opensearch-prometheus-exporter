package org.opensearch.plugin.prometheus;

import io.prometheus.client.Collector;
import org.opensearch.plugin.prometheus.collector.PrometheusMetricsCatalog;
import org.opensearch.plugin.prometheus.collector.PrometheusMetricsCollector;
import org.opensearch.plugin.prometheus.filter.PrometheusActionFilter;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Generates {@code METRICS.md}, the list of all metrics exposed by the plugin, from the metric definitions in the code.
 * <p>
 * Run {@code ./gradlew updateMetricsDoc} to regenerate the file, and {@code ./gradlew checkMetricsDoc} (part of
 * {@code check}) to verify it is up to date.
 */
public final class MetricsDocumentation {

    private static final String PREFIX = "opensearch_";
    private static final List<String> NODE_LABELS = PrometheusMetricsCatalog.NODE_LABEL_NAMES;

    // Section titles, keyed by the first word of the metric name (after the prefix). Every metric group needs an entry,
    // so that new groups get a proper title.
    private static final Map<String, String> SECTION_TITLES = Map.ofEntries(
            Map.entry("metrics", "Exporter"),
            Map.entry("cluster", "Cluster"),
            Map.entry("node", "Node"),
            Map.entry("indices", "Node indices"),
            Map.entry("index", "Index level"),
            Map.entry("transport", "Transport"),
            Map.entry("http", "HTTP"),
            Map.entry("threadpool", "Thread pools"),
            Map.entry("ingest", "Ingest"),
            Map.entry("circuitbreaker", "Circuit breakers"),
            Map.entry("script", "Scripts"),
            Map.entry("process", "Process"),
            Map.entry("jvm", "JVM"),
            Map.entry("os", "Operating system"),
            Map.entry("fs", "File system"),
            Map.entry("search", "Search backpressure"),
            Map.entry("action", "Transport actions")
    );

    private MetricsDocumentation() {}

    /** A documented metric. */
    private record Metric(String name, String type, String help, List<String> labels) {}

    private static final String HEADER = String.format(Locale.ROOT, """
            <!-- This file is generated by ./gradlew updateMetricsDoc. Do not edit it manually. -->

            # Metrics

            All metrics exposed by the plugin, generated from the metric definitions in the code. Metric names use \
            the default `%s` prefix, which can be changed with the `prometheus.metric_name.prefix` setting.

            Every metric has the `cluster` label. Metrics with the **node** scope also have the `node` and `nodeid` \
            labels of the node they describe; the `Labels` column lists only the additional labels. Some metrics are \
            exposed only when the related setting is enabled or when OpenSearch reports the statistic; see the \
            [README](README.md) for details.

            """, PREFIX);

    /**
     * Generate the content of {@code METRICS.md}.
     * @return markdown content
     * @throws IllegalStateException if a metric belongs to a group without an entry in {@link #SECTION_TITLES}
     */
    public static String generate() {
        final var sections = new LinkedHashMap<String, List<Metric>>();
        for (final var metric : metrics()) {
            sections.computeIfAbsent(sectionTitle(metric.name()), k -> new ArrayList<>()).add(metric);
        }

        final var md = new StringBuilder(HEADER);
        md.append("| Section | Metrics |\n| --- | --- |\n");
        for (final var section : sections.entrySet()) {
            md.append("| [").append(section.getKey()).append("](#").append(anchor(section.getKey())).append(") | ")
                    .append(section.getValue().size()).append(" |\n");
        }

        for (final var section : sections.entrySet()) {
            md.append("\n## ").append(section.getKey()).append("\n\n");
            md.append("| Metric | Type | Scope | Labels | Description |\n| --- | --- | --- | --- | --- |\n");
            for (final var metric : section.getValue()) {
                final var node = metric.labels().size() >= NODE_LABELS.size()
                        && metric.labels().subList(0, NODE_LABELS.size()).equals(NODE_LABELS);
                final var extra = metric.labels().subList(node ? NODE_LABELS.size() : 1, metric.labels().size());
                md.append("| `").append(metric.name()).append("` | ")
                        .append(metric.type()).append(" | ")
                        .append(node ? "node" : "cluster").append(" | ")
                        .append(extra.isEmpty() ? "" : "`" + String.join("`, `", extra) + "`").append(" | ")
                        .append(escape(metric.help())).append(" |\n");
            }
        }
        return md.toString();
    }

    /**
     * Get the section title of a metric, from the first word of its name after the prefix.
     * @param metricName full metric name, including the prefix
     * @return section title
     * @throws IllegalStateException if the metric group has no entry in {@link #SECTION_TITLES}
     */
    static String sectionTitle(final String metricName) {
        final var group = metricName.substring(PREFIX.length()).split("_", 2)[0];
        final var title = SECTION_TITLES.get(group);
        if (title == null) {
            throw new IllegalStateException("No section title for metric group '" + group + "' (metric " + metricName
                    + "). Add it to SECTION_TITLES in " + MetricsDocumentation.class.getSimpleName() + ".");
        }
        return title;
    }

    private static List<Metric> metrics() {
        final var metrics = new ArrayList<Metric>();

        final var catalog = new PrometheusMetricsCatalog("cluster", PREFIX);
        new PrometheusMetricsCollector(catalog, true, true).registerMetrics();
        for (final var d : catalog.getMetricDescriptions()) {
            metrics.add(new Metric(d.name(), d.type(), d.help(), d.labels()));
        }

        // The action filter keeps its own registry; its label names are taken from its (pre-created) samples.
        // The registry returns metric families in hash order of the collector objects, which differs between JVM runs,
        // so sort them by name to keep the generated file stable.
        final var actionFilter = new PrometheusActionFilter(PREFIX);
        final var actionMetrics = new ArrayList<Metric>();
        for (final var family : Collections.list(actionFilter.metricFamilySamples("c", "n", "id"))) {
            final var labels = new LinkedHashSet<String>();
            family.samples.forEach(sample -> labels.addAll(sample.labelNames));
            labels.remove("le");
            final var name = family.type == Collector.Type.COUNTER ? family.name + "_total" : family.name;
            actionMetrics.add(new Metric(name, family.type.name().toLowerCase(Locale.ROOT), family.help, List.copyOf(labels)));
        }
        actionMetrics.sort(Comparator.comparing(Metric::name));
        metrics.addAll(actionMetrics);
        return metrics;
    }

    private static String anchor(final String title) {
        return title.toLowerCase(Locale.ROOT).replace(' ', '-');
    }

    private static String escape(final String text) {
        return text.replace("|", "\\|").replace("\n", " ");
    }

    /**
     * Writes or checks {@code METRICS.md}.
     * @param args {@code [--check] <path to METRICS.md>}
     * @throws IOException if the file cannot be read or written
     */
    public static void main(final String[] args) throws IOException {
        final var check = args.length == 2 && "--check".equals(args[0]);
        if (args.length != (check ? 2 : 1)) {
            throw new IllegalArgumentException("Usage: MetricsDocumentation [--check] <path to METRICS.md>");
        }
        final var path = Path.of(args[args.length - 1]);
        final var content = generate();
        if (check) {
            final var current = Files.exists(path) ? Files.readString(path, StandardCharsets.UTF_8) : "";
            if (!current.equals(content)) {
                // An uncaught exception makes the JavaExec task, and thus the build, fail.
                throw new IllegalStateException(path + " is out of date. Run ./gradlew updateMetricsDoc and commit the result.");
            }
        } else {
            Files.writeString(path, content, StandardCharsets.UTF_8);
        }
    }
}
