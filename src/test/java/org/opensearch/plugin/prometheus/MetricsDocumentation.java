package org.opensearch.plugin.prometheus;

import io.prometheus.client.Collector;
import org.opensearch.plugin.prometheus.collector.PrometheusMetricsCatalog;
import org.opensearch.plugin.prometheus.collector.PrometheusMetricsCatalog.MetricDescription;
import org.opensearch.plugin.prometheus.collector.PrometheusMetricsCollector;
import org.opensearch.plugin.prometheus.filter.PrometheusActionFilter;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Generates {@code METRICS.md}, the list of all metrics exposed by the plugin, from the metric definitions in the code.
 * <p>
 * Run {@code ./gradlew updateMetricsDoc} to regenerate the file, and {@code ./gradlew checkMetricsDoc} (part of
 * {@code check}) to verify it is up to date.
 */
public final class MetricsDocumentation {

    private static final String PREFIX = "opensearch_";
    private static final List<String> NODE_LABELS = PrometheusMetricsCatalog.NODE_LABEL_NAMES;

    // Section titles, keyed by the first word of the metric name (after the prefix). Unknown words get their own
    // section titled after the word, so new metric groups are documented without changes here.
    private static final Map<String, String> SECTION_TITLES = Map.ofEntries(
            Map.entry("metrics", "Exporter"),
            Map.entry("cluster", "Cluster"),
            Map.entry("node", "Node"),
            Map.entry("indices", "Node indices"),
            Map.entry("index", "Index level"),
            Map.entry("transport", "Transport"),
            Map.entry("http", "HTTP"),
            Map.entry("threadpool", "Thread pools"),
            Map.entry("ingest", "Ingest"),
            Map.entry("circuitbreaker", "Circuit breakers"),
            Map.entry("script", "Scripts"),
            Map.entry("process", "Process"),
            Map.entry("jvm", "JVM"),
            Map.entry("os", "Operating system"),
            Map.entry("fs", "File system"),
            Map.entry("search", "Search backpressure"),
            Map.entry("action", "Transport actions")
    );

    private MetricsDocumentation() {}

    /** A documented metric. */
    private record Metric(String name, String type, String help, List<String> labels) {}

    /**
     * Generate the content of {@code METRICS.md}.
     * @return markdown content
     */
    public static String generate() {
        Map<String, List<Metric>> sections = new LinkedHashMap<>();
        for (Metric metric : metrics()) {
            String word = metric.name().substring(PREFIX.length()).split("_", 2)[0];
            String title = SECTION_TITLES.getOrDefault(word, word.substring(0, 1).toUpperCase(Locale.ROOT) + word.substring(1));
            sections.computeIfAbsent(title, k -> new ArrayList<>()).add(metric);
        }

        StringBuilder md = new StringBuilder();
        md.append("<!-- This file is generated by ./gradlew updateMetricsDoc. Do not edit it manually. -->\n\n");
        md.append("# Metrics\n\n");
        md.append("All metrics exposed by the plugin, generated from the metric definitions in the code. Metric names use ");
        md.append("the default `").append(PREFIX).append("` prefix, which can be changed with the ");
        md.append("`prometheus.metric_name.prefix` setting.\n\n");
        md.append("Every metric has the `cluster` label. Metrics with the **node** scope also have the `node` and `nodeid` ");
        md.append("labels of the node they describe; the `Labels` column lists only the additional labels. Some metrics ");
        md.append("are exposed only when the related setting is enabled or when OpenSearch reports the statistic; see the ");
        md.append("[README](README.md) for details.\n\n");

        md.append("| Section | Metrics |\n| --- | --- |\n");
        for (Map.Entry<String, List<Metric>> section : sections.entrySet()) {
            md.append("| [").append(section.getKey()).append("](#").append(anchor(section.getKey())).append(") | ")
                    .append(section.getValue().size()).append(" |\n");
        }

        for (Map.Entry<String, List<Metric>> section : sections.entrySet()) {
            md.append("\n## ").append(section.getKey()).append("\n\n");
            md.append("| Metric | Type | Scope | Labels | Description |\n| --- | --- | --- | --- | --- |\n");
            for (Metric metric : section.getValue()) {
                boolean node = metric.labels().size() >= NODE_LABELS.size()
                        && metric.labels().subList(0, NODE_LABELS.size()).equals(NODE_LABELS);
                List<String> extra = metric.labels().subList(node ? NODE_LABELS.size() : 1, metric.labels().size());
                md.append("| `").append(metric.name()).append("` | ")
                        .append(metric.type()).append(" | ")
                        .append(node ? "node" : "cluster").append(" | ")
                        .append(extra.isEmpty() ? "" : "`" + String.join("`, `", extra) + "`").append(" | ")
                        .append(escape(metric.help())).append(" |\n");
            }
        }
        return md.toString();
    }

    private static List<Metric> metrics() {
        List<Metric> metrics = new ArrayList<>();

        PrometheusMetricsCatalog catalog = new PrometheusMetricsCatalog("cluster", PREFIX);
        new PrometheusMetricsCollector(catalog, true, true).registerMetrics();
        for (MetricDescription d : catalog.getMetricDescriptions()) {
            metrics.add(new Metric(d.name(), d.type(), d.help(), d.labels()));
        }

        // The action filter keeps its own registry; its label names are taken from its (pre-created) samples.
        // The registry returns metric families in hash order of the collector objects, which differs between JVM runs,
        // so sort them by name to keep the generated file stable.
        PrometheusActionFilter actionFilter = new PrometheusActionFilter(PREFIX);
        List<Metric> actionMetrics = new ArrayList<>();
        for (Collector.MetricFamilySamples family : Collections.list(actionFilter.metricFamilySamples("c", "n", "id"))) {
            Set<String> labels = new LinkedHashSet<>();
            family.samples.forEach(sample -> labels.addAll(sample.labelNames));
            labels.remove("le");
            String name = family.type == Collector.Type.COUNTER ? family.name + "_total" : family.name;
            actionMetrics.add(new Metric(name, family.type.name().toLowerCase(Locale.ROOT), family.help, List.copyOf(labels)));
        }
        actionMetrics.sort(Comparator.comparing(Metric::name));
        metrics.addAll(actionMetrics);
        return metrics;
    }

    private static String anchor(String title) {
        return title.toLowerCase(Locale.ROOT).replace(' ', '-');
    }

    private static String escape(String text) {
        return text.replace("|", "\\|").replace("\n", " ");
    }

    /**
     * Writes or checks {@code METRICS.md}.
     * @param args {@code [--check] <path to METRICS.md>}
     * @throws IOException if the file cannot be read or written
     */
    public static void main(String[] args) throws IOException {
        boolean check = args.length == 2 && "--check".equals(args[0]);
        if (args.length != (check ? 2 : 1)) {
            throw new IllegalArgumentException("Usage: MetricsDocumentation [--check] <path to METRICS.md>");
        }
        Path path = Path.of(args[args.length - 1]);
        String content = generate();
        if (check) {
            String current = Files.exists(path) ? Files.readString(path, StandardCharsets.UTF_8) : "";
            if (current.equals(content) == false) {
                // An uncaught exception makes the JavaExec task, and thus the build, fail.
                throw new IllegalStateException(path + " is out of date. Run ./gradlew updateMetricsDoc and commit the result.");
            }
        } else {
            Files.writeString(path, content, StandardCharsets.UTF_8);
        }
    }
}
